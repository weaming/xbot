/** 上下文压缩提示词。 */
export function buildCompactPrompt(instruction?: string): string {
    return [
        '请对上述对话历史进行高保真、高信息密度的结构化总结，输出供后续对话直接复用的上下文背景。',
        '总结应涵盖以下关键维度：',
        '1. 核心任务与背景目标（用户核心诉求与当前项目状态）',
        '2. 已确认的事实、关键技术决策与已完成工作（修改了哪些文件、实现了哪些功能）',
        '3. 遗留问题、待办事项（Todo）与下一步计划',
        '4. 本次对话新出现的约束、偏好或临时口径（系统提示已覆盖的不要写）',
        '要求：',
        '- 系统提示（含 AGENTS.md 等规则文件、环境说明、工具说明）已常驻生效，不要在摘要中复述、概括或引用其中内容；工作目录、操作系统、编码风格、命名规范、提交规范、交互语言等一律省略。',
        '- 同一条信息若系统提示里已有（即使对话中也出现过），直接省略；只保留对话本身产生的新信息。',
        '- 不要包含工具调用名称、参数细节或原始终端输出，只保留最终关键结果与事实。',
        '- 只输出结构化摘要正文，必要时保留关键文件路径或代码关键签名。',
        instruction ? `用户特定压缩要求：${instruction}` : '',
    ].filter(Boolean).join('\n');
}
